test_that("function targets create _fn suffix for function object tracking", {
  tmp_dir <- withr::local_tempdir()

  auto_dir <- file.path(tmp_dir, "R", "auto")
  dir.create(auto_dir, recursive = TRUE)
  writeLines(
    c(
      "data <- 1:10",
      "process <- function(data) data * 2"
    ),
    file.path(auto_dir, "pipeline.R")
  )

  result <- generate_targets(path = tmp_dir, write = FALSE)

  # Should have _fn suffix for function (using get() to avoid cycles)
  expect_true(any(grepl('tar_target\\(process_fn, get\\("process"', result)))

  # Result target should call _fn version
  expect_true(any(grepl("tar_target\\(process, process_fn\\(data\\)\\)", result)))

  # Constants should not have _fn suffix
  expect_true(any(grepl("tar_target\\(data, data\\)", result)))
  expect_false(any(grepl("data_fn", result)))
})

test_that("constants evaluate their value directly for change detection", {
  # Constants don't need _fn_ pattern because tar_target(const, const)
  # evaluates to the actual value, which targets hashes.
  # If the constant's value changes, the hash changes and target is invalidated.
  result <- make_constant_target("params")
  expect_equal(result, "  tar_target(params, params)")

  # This is different from functions where the body is encapsulated
  # and not visible in the call expression
})

