test_that("changing function source changes generated target", {
  tmp_dir <- withr::local_tempdir()

  auto_dir <- file.path(tmp_dir, "R", "auto")
  dir.create(auto_dir, recursive = TRUE)

  # Write initial function
  writeLines(
    c("process <- function(data) data * 2"),
    file.path(auto_dir, "pipeline.R")
  )
  result1 <- generate_targets(path = tmp_dir, write = FALSE)

  # Change function body
  writeLines(
    c("process <- function(data) data * 3"),
    file.path(auto_dir, "pipeline.R")
  )
  result2 <- generate_targets(path = tmp_dir, write = FALSE)

  # The generated code should be different
  expect_false(identical(result1, result2))
  expect_true(any(grepl("data \\* 2", result1)))
  expect_true(any(grepl("data \\* 3", result2)))
})

