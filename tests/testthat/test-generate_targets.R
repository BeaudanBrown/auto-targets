test_that("make_function_target embeds source and tracks args", {
  # Function with args
  source <- "my_func <- function(x, y) x + y"
  result <- make_function_target("my_func", list(x = NULL, y = NULL), source)
  expect_type(result, "character")
  expect_length(result, 1)
  expect_true(grepl("tar_target\\(my_func,", result))
  expect_true(grepl("\\.fn\\(x, y\\)", result))
  expect_true(grepl("function\\(x, y\\)", result))

  # Function with no args
  source <- "no_args <- function() 42"
  result <- make_function_target("no_args", list(), source)
  expect_true(grepl("tar_target\\(no_args,", result))
  expect_true(grepl("\\.fn\\(\\)", result))
})

test_that("make_function_target with _file suffix adds format", {
