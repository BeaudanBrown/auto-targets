test_that("generate_targets handles file targets for constants and functions", {
  tmp_dir <- withr::local_tempdir()

  auto_dir <- file.path(tmp_dir, "R", "auto")
  dir.create(auto_dir, recursive = TRUE)
  writeLines(
    c(
      "raw_data_file <- \"data/input.csv\"",
      "threshold <- 0.05",
      "output_file <- function(data) {",
      "  write.csv(data, \"output.csv\")",
      "  \"output.csv\"",
      "}",
      "process <- function(raw_data_file) read.csv(raw_data_file)"
    ),
    file.path(auto_dir, "pipeline.R")
  )

  result <- generate_targets(path = tmp_dir, write = FALSE)

  # Constant file target
  expect_true(any(grepl('tar_target\\(raw_data_file, raw_data_file, format = "file"\\)', result)))

  # Regular constant (no format)
  expect_true(any(grepl('tar_target\\(threshold, threshold\\)', result)))

  # Function file target (result has format = "file", fn uses get())
  expect_true(any(grepl('tar_target\\(output_file_fn, get\\("output_file"', result)))
  expect_true(any(grepl('tar_target\\(output_file, output_file_fn\\(data\\), format = "file"\\)', result)))

  # Regular function (fn uses get())
  expect_true(any(grepl('tar_target\\(process_fn, get\\("process"', result)))
  expect_true(any(grepl('tar_target\\(process, process_fn\\(raw_data_file\\)\\)', result)))
})

test_that("generated target names are valid R identifiers", {
  tmp_dir <- withr::local_tempdir()

  auto_dir <- file.path(tmp_dir, "R", "auto")
  dir.create(auto_dir, recursive = TRUE)
  writeLines(
    c(
      "process <- function(data) data * 2"
    ),
    file.path(auto_dir, "pipeline.R")
  )

  result <- generate_targets(path = tmp_dir, write = FALSE)

  # All generated code should parse without error
  expect_error(parse(text = result), NA)

  # Extract target names and verify they're valid R identifiers
  target_names <- gsub(".*tar_target\\(([^,]+),.*", "\\1", result[grep("tar_target", result)])
  target_names <- trimws(target_names)

  for (name in target_names) {
    # Should not start with a dot (targets requirement)
    expect_false(grepl("^\\.", name), info = paste("Name starts with dot:", name))
    # Should not start with underscore (R syntax error)
    expect_false(grepl("^_", name), info = paste("Name starts with underscore:", name))
    # Should be a valid R identifier
    expect_true(make.names(name) == name, info = paste("Invalid R identifier:", name))
  }
})

test_that("generated targets can be validated by targets package", {
  skip_if_not_installed("targets")

  tmp_dir <- withr::local_tempdir()

  auto_dir <- file.path(tmp_dir, "R", "auto")
  dir.create(auto_dir, recursive = TRUE)
  writeLines(
    c(
      "data <- 1:10",
      "process <- function(data) data * 2"
    ),
    file.path(auto_dir, "pipeline.R")
  )

  result <- generate_targets(path = tmp_dir, write = FALSE)

  # Create a valid targets list (using targets::tar_target explicitly)
  code <- paste0("list(\n", paste(result, collapse = ",\n"), "\n)")
  targets_list <- eval(parse(text = code), envir = asNamespace("targets"))

  # Check that target names are valid for targets package
  for (target in targets_list) {
    # targets requires names that don't start with dot
    expect_false(
      grepl("^\\.", target$settings$name),
      info = paste("Target name starts with dot:", target$settings$name)
    )
  }
})
